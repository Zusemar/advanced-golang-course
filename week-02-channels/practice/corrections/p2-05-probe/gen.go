// Command gen writes sel2.go, sel4.go ... sel128.go: step 3's select loop for
// 2, 4, 8, 16, 32, 64 and 128 inputs. A select statement's cases are fixed when
// it is compiled, so a loop over n inputs needs n cases written out. It also
// writes ready_test.go, the same n-case select for BenchmarkSelectOnly.
//
// Run it with go generate from this directory.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"
)

var sizes = []int{2, 4, 8, 16, 32, 64, 128}

const header = `// Code generated by gen.go; DO NOT EDIT.

// SPDX-License-Identifier: Apache-2.0
// Part of "Advanced Golang". Code and tests are Apache-2.0; see LICENSE-CODE.

package probe

import "course/w02/practice/feed"
`

func main() {
	for _, n := range sizes {
		var b bytes.Buffer
		b.WriteString(header)
		writeSelect(&b, n)
		write(fmt.Sprintf("sel%d.go", n), b.Bytes())
	}
	var b bytes.Buffer
	b.WriteString(header)
	for _, n := range sizes {
		writeReady(&b, n)
	}
	write("ready_test.go", b.Bytes())
}

// writeSelect writes SelectN: step 3 with n cases instead of two.
func writeSelect(b *bytes.Buffer, n int) {
	fmt.Fprintf(b, `
// Select%[1]d merges exactly %[1]d inputs with one select loop, like step 3: a
// closed input's variable is set to nil, which switches its case off, and the
// loop ends when no input is left open. It panics if len(ins) is not %[1]d.
func Select%[1]d(ins ...<-chan feed.Item) <-chan feed.Item {
	if len(ins) != %[1]d {
		panic("Select%[1]d: want exactly %[1]d inputs")
	}
	%[2]s := %[3]s
	out := make(chan feed.Item)
	go func() {
		defer close(out)
		for open := %[1]d; open > 0; {
			select {
`, n, vars(n, "c%d"), vars(n, "ins[%d]"))
	for k := range n {
		fmt.Fprintf(b, `			case it, ok := <-c%[1]d:
				if !ok {
					c%[1]d = nil
					open--
					continue
				}
				out <- it
`, k)
	}
	b.WriteString(`			}
		}
	}()
	return out
}
`)
}

// writeReady writes readyN: the same n-case select with nothing else around
// it. Every channel has a buffer of one and holds one item, so every case is
// always ready. The chosen item is put back, so the next select finds all n
// ready again. No other goroutine is involved.
func writeReady(b *bytes.Buffer, n int) {
	fmt.Fprintf(b, `
// ready%[1]d runs iters selects over %[1]d channels that are always ready.
func ready%[1]d(cs []chan feed.Item, iters int) {
	%[2]s := %[3]s
	for range iters {
		select {
`, n, vars(n, "c%d"), vars(n, "cs[%d]"))
	for k := range n {
		fmt.Fprintf(b, `		case it, ok := <-c%[1]d:
			if !ok {
				panic("closed")
			}
			c%[1]d <- it
`, k)
	}
	b.WriteString(`		}
	}
}
`)
}

// vars returns "f(0), f(1), ..., f(n-1)" for a format f with one %d.
func vars(n int, f string) string {
	s := make([]string, n)
	for k := range n {
		s[k] = fmt.Sprintf(f, k)
	}
	return strings.Join(s, ", ")
}

func write(name string, src []byte) {
	out, err := format.Source(src)
	if err != nil {
		log.Fatalf("%s: %v", name, err)
	}
	if err := os.WriteFile(name, out, 0o644); err != nil {
		log.Fatal(err)
	}
}
